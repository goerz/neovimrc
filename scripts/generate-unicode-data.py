#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Generate lua/libraries/_unicode_data.lua from the Unicode Character Database.

The generated table holds what lua/libraries/_unicode.lua needs for NFC
normalization (canonical decompositions, composition exclusions, canonical
combining classes, NFC quick-check values) and the set of combining marks
(general category M).

Usage: scripts/generate-unicode-data.py [VERSION]

VERSION is a Unicode version such as 18.0.0 (default: latest). Unicode's
stability policy guarantees that NFC of existing text never changes, so
regenerating only matters for characters encoded after the current version.
"""

import re
import sys
import urllib.request
from pathlib import Path

OUTFILE = Path(__file__).resolve().parent.parent / "lua" / "libraries" / "_unicode_data.lua"


def fetch(version, name):
    url = f"https://www.unicode.org/Public/{version}/ucd/{name}"
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def ranges(codepoints):
    """Collapse a set of code points (or a dict cp → value) into ranges."""
    if isinstance(codepoints, dict):
        items = sorted(codepoints.items())
    else:
        items = [(cp, None) for cp in sorted(codepoints)]
    result = []
    for cp, value in items:
        if result and result[-1][1] == cp - 1 and result[-1][2] == value:
            result[-1][1] = cp
        else:
            result.append([cp, cp, value])
    return result


def parse_property_file(text):
    """Yield (first, last, fields) for each data line of a UCD property file."""
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [field.strip() for field in line.split(";")]
        first, _, last = fields[0].partition("..")
        yield int(first, 16), int(last or first, 16), fields[1:]


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else "latest"
    unicode_data = fetch(version, "UnicodeData.txt")
    norm_props = fetch(version, "DerivedNormalizationProps.txt")
    match = re.search(r"DerivedNormalizationProps-(\d+\.\d+\.\d+)\.txt", norm_props)
    full_version = match.group(1) if match else version

    decomposition = {}  # cp → list of cp (canonical, single level)
    ccc = {}  # cp → canonical combining class (nonzero only)
    marks = set()  # general category Mn, Mc, Me
    for line in unicode_data.splitlines():
        fields = line.split(";")
        cp = int(fields[0], 16)
        if fields[2] in ("Mn", "Mc", "Me"):
            marks.add(cp)
        if fields[3] != "0":
            ccc[cp] = int(fields[3])
        if fields[5] and not fields[5].startswith("<"):
            decomposition[cp] = [int(x, 16) for x in fields[5].split()]

    exclusions = set()  # Full_Composition_Exclusion, restricted to decomposables
    quick_check = {}  # cp → "N" or "M" (NFC_QC; everything else is "Y")
    for first, last, fields in parse_property_file(norm_props):
        if fields[0] == "Full_Composition_Exclusion":
            exclusions.update(cp for cp in range(first, last + 1) if cp in decomposition)
        elif fields[0] == "NFC_QC":
            for cp in range(first, last + 1):
                quick_check[cp] = fields[1]

    def hex_list(cps):
        return ", ".join(f"0x{cp:04X}" for cp in cps)

    out = [
        f"-- Generated by scripts/generate-unicode-data.py from Unicode {full_version}.",
        "-- Do not edit. See lua/libraries/_unicode.lua for how it is used.",
        "-- stylua: ignore",
        "return {",
        f'  version = "{full_version}",',
        "  -- Canonical decompositions (single level): [cp] = { cp, ... }",
        "  decomposition = {",
    ]
    out += [f"    [0x{cp:04X}] = {{ {hex_list(d)} }}," for cp, d in sorted(decomposition.items())]
    out += [
        "  },",
        "  -- Code points with a canonical decomposition that never recompose",
        "  -- (Full_Composition_Exclusion)",
        "  composition_exclusions = {",
    ]
    excl = sorted(exclusions)
    out += [f"    {hex_list(excl[i:i + 8])}," for i in range(0, len(excl), 8)]
    out += [
        "  },",
        "  -- Nonzero canonical combining classes: { first, last, class }",
        "  combining_class = {",
    ]
    out += [f"    {{ 0x{a:04X}, 0x{b:04X}, {v} }}," for a, b, v in ranges(ccc)]
    out += [
        "  },",
        '  -- NFC quick check values other than "Y": { first, last, "N" or "M" }',
        "  nfc_quick_check = {",
    ]
    out += [f'    {{ 0x{a:04X}, 0x{b:04X}, "{v}" }},' for a, b, v in ranges(quick_check)]
    out += [
        "  },",
        "  -- Combining marks (general category Mn, Mc, Me): { first, last }",
        "  marks = {",
    ]
    out += [f"    {{ 0x{a:04X}, 0x{b:04X} }}," for a, b, _ in ranges(marks)]
    out += ["  },", "}", "", "-- vim: ts=2 sts=2 sw=2 et fdm=marker fmr={,} nofen", ""]

    OUTFILE.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUTFILE} (Unicode {full_version})")


if __name__ == "__main__":
    main()
